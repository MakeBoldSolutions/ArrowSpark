import { chromium, firefox } from '../../../../web/node_modules/playwright/index.mjs';
import { writeFile } from 'node:fs/promises';
const isFirefox = process.argv.includes('--firefox');
const browser = isFirefox ? await firefox.launch() : await chromium.launch({channel:'chrome'});
const page = await browser.newPage({ viewport:{width:390,height:844},hasTouch:true });
const errors=[]; page.on('pageerror',e=>errors.push(String(e)));
page.on('console',m=>{if(m.type()==='error' && /SCRIPT ERROR|Parse Error|Nonexistent|Invalid call/.test(m.text()))errors.push(m.text());});
await page.goto('http://localhost:4331/play/');
await page.frameLocator('iframe').locator('body[data-engine-state="started"]').waitFor({state:'attached',timeout:60000});
await page.waitForTimeout(3000);
await page.locator('[data-game-host]').scrollIntoViewIfNeeded();
let area=await page.locator('iframe').boundingBox();
await page.touchscreen.tap(area.x+area.width/2,area.y+area.height*0.5);
await page.waitForTimeout(1500);
await page.touchscreen.tap(area.x+25,area.y+340);
await page.waitForTimeout(800);
const before=await page.screenshot({clip:{x:area.x,y:area.y,width:area.width,height:25}});
await page.screenshot({path:new URL(isFirefox ? 'firefox-journey-before.png' : 'journey-before.png',import.meta.url).pathname.replace(/^\/(\w:)/,'$1')});
const iframe=await page.locator('iframe').elementHandle();
for(let i=0;i<2;i++){await page.setViewportSize({width:844,height:390});await page.waitForTimeout(200);await page.setViewportSize({width:390,height:844});await page.waitForTimeout(300);}
await page.setViewportSize({width:390,height:740});await page.waitForTimeout(300);
await page.setViewportSize({width:390,height:844});await page.waitForTimeout(500);
await page.locator('[data-game-host]').scrollIntoViewIfNeeded();
area=await page.locator('iframe').boundingBox();
const after=await page.screenshot({clip:{x:area.x,y:area.y,width:area.width,height:25}});
if(!before.equals(after))throw new Error('Visible status changed during resize cycle');
if(!await iframe.evaluate(n=>n===document.querySelector('iframe')))throw new Error('iframe replaced');
await page.touchscreen.tap(area.x+40,area.y+area.height-25);await page.waitForTimeout(400);
await page.screenshot({path:new URL(isFirefox ? 'firefox-journey-pause.png' : 'journey-pause.png',import.meta.url).pathname.replace(/^\/(\w:)/,'$1')});
await page.keyboard.press('Escape');await page.waitForTimeout(300);
if(errors.length)throw new Error(errors.join('\n'));
await writeFile(new URL(isFirefox ? 'firefox-journey.json' : 'journey.json',import.meta.url),JSON.stringify({browser:browser.version(),statusPixelsRetained:true,iframeRetained:true,errors,physicalDeviceEvidence:false},null,2));
console.log('PASS: Chrome real-export touch interaction, two rotation cycles, height change, retained status pixels/iframe, menu and cancel.');
await browser.close();
